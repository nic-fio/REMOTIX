#!/bin/bash
# 19-shader.sh — compiles the conversion shader to SPIR-V and writes it as a
# C header (`src/vulkanvideo_rgb_nv12_spv.h`), which is KEPT in the
# repository: the product does not need the shader compiler, only whoever
# changes the shader does.
#
#   bash benches/19-vulkan/19-shader.sh            (from the root of the tree)
#
# Needs `glslc` (package `glslc`, shaderc) or `glslangValidator`
# (`glslang-tools`); the server's devroot has both.
set -eu
TREE=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
SOURCE=$TREE/src/vulkanvideo_rgb_nv12.comp
OUTPUT=$TREE/src/vulkanvideo_rgb_nv12_spv.h
if command -v glslc >/dev/null; then
	glslc -O --target-env=vulkan1.3 -fshader-stage=compute -mfmt=c -o "$OUTPUT.tmp" "$SOURCE"
	{
		echo "/* generated by benches/19-vulkan/19-shader.sh from src/vulkanvideo_rgb_nv12.comp: do not edit by hand */"
		# glslc writes `{0x..,0x..,}`: the braces are removed, so the header fits inside an initializer
		sed -e 's/^{//' -e 's/}$//' "$OUTPUT.tmp"
	} > "$OUTPUT"
	rm -f "$OUTPUT.tmp"
elif command -v glslangValidator >/dev/null; then
	glslangValidator -V --target-env vulkan1.3 -S comp -o "$OUTPUT.spv" "$SOURCE"
	{
		echo "/* generated by benches/19-vulkan/19-shader.sh from src/vulkanvideo_rgb_nv12.comp: do not edit by hand */"
		od -An -v -t x4 -w16 "$OUTPUT.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1,/g'
	} > "$OUTPUT"
	rm -f "$OUTPUT.spv"
else
	echo "⛔ neither glslc nor glslangValidator" >&2
	exit 1
fi
echo "written $OUTPUT ($(wc -c < "$OUTPUT") bytes)"
