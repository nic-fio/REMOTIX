/*
 * vulkanvideo.c — encoding on the card with Vulkan Video.  The why and the
 * rules are in `vulkanvideo.h`.
 *
 * The file follows the order of `vadirect.c`:
 *   1. the tools (errors, time, memory);
 *   2. the level, as ffmpeg guessed it (the same tables as vadiretta);
 *   3. the device: instance, card chosen by DRM node, queues, extensions;
 *   4. profiles and capabilities;
 *   5. opening: session, parameters (StdVideo*), headers, images,
 *      shader, buffers;
 *   6. input: from memory and from DMA-BUF, and the conversion on the card;
 *   7. one frame's round: begin/control/encode/end, wait, bytes.
 *
 * ⛔ The loader does NOT export the video extension functions: they are fetched
 *    with `vkGetInstanceProcAddr` / `vkGetDeviceProcAddr`, once, and live in
 *    the device (`f.`).  The rest is plain Vulkan 1.3.
 */
