/* The headers from the driver, one parameter set per call, each with its
 * start code if the driver does not put one. */
static bool take_header(VulkanVideo *v, bool vps, bool sps, bool pps, char *error,
                                size_t error_byte)
{
	VkVideoEncodeH264SessionParametersGetInfoKHR g264 = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H264_SESSION_PARAMETERS_GET_INFO_KHR,
		.writeStdSPS = sps, .writeStdPPS = pps, .stdSPSId = 0, .stdPPSId = 0,
	};
	VkVideoEncodeH265SessionParametersGetInfoKHR g265 = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H265_SESSION_PARAMETERS_GET_INFO_KHR,
		.writeStdVPS = vps, .writeStdSPS = sps, .writeStdPPS = pps,
	};
	VkVideoEncodeSessionParametersGetInfoKHR gi = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_SESSION_PARAMETERS_GET_INFO_KHR,
		.pNext = v->r.codec == VULKANVIDEO_H264 ? (void *) &g264 : (void *) &g265,
		.videoSessionParameters = v->parameters,
	};
	VkVideoEncodeH264SessionParametersFeedbackInfoKHR f264 = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H264_SESSION_PARAMETERS_FEEDBACK_INFO_KHR };
	VkVideoEncodeH265SessionParametersFeedbackInfoKHR f265 = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H265_SESSION_PARAMETERS_FEEDBACK_INFO_KHR };
	VkVideoEncodeSessionParametersFeedbackInfoKHR fb = {
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_SESSION_PARAMETERS_FEEDBACK_INFO_KHR,
		.pNext = v->r.codec == VULKANVIDEO_H264 ? (void *) &f264 : (void *) &f265,
	};
	size_t n = 0;
	uint8_t tmp[MAX_HEADERS];
	VkResult r;

	r = v->d->f.GetEncodedVideoSessionParametersKHR(v->d->device, &gi, &fb, &n, NULL);
	if (r != VK_SUCCESS)
		FAIL("vkGetEncodedVideoSessionParametersKHR (size): %s", vk_name(r));
	if (!n || n > sizeof tmp)
		FAIL("header of %zu bytes: out of bounds", n);
	r = v->d->f.GetEncodedVideoSessionParametersKHR(v->d->device, &gi, &fb, &n, tmp);
	if (r != VK_SUCCESS)
		FAIL("vkGetEncodedVideoSessionParametersKHR: %s", vk_name(r));
	if (fb.hasOverrides)
		v->decl.driver_has_changed_parameters = true;
	{
		bool with_code = n >= 4 && tmp[0] == 0 && tmp[1] == 0 && (tmp[2] == 1 || (tmp[2] == 0 && tmp[3] == 1));
		size_t needs = n + (with_code ? 0 : 4);
		if (v->headers_byte + needs > sizeof v->headers)
			FAIL("the headers exceed %zu bytes", sizeof v->headers);
		if (!with_code) {
			memcpy(v->headers + v->headers_byte, "\0\0\0\1", 4);
			v->headers_byte += 4;
		}
		memcpy(v->headers + v->headers_byte, tmp, n);
		v->headers_byte += n;
	}
	return true;
}

/*
 * ⛔ THE LEVEL RADV WRITES IN HEVC: `[M]` 1 Oct 2026, Mesa 25.0.7, for a
 *    level 4.0 the VPS and SPS carry `general_level_idc = 40` instead of
 *    120 (= 4.0 × 30, H.265 A.4): the driver uses the H.264 alphabet (× 10).
 *    ffprobe reads it as "40", and the string for the browser would become
 *    `hev1.1.6.L40.B0` — a level that does not exist.  ⇒ The byte is fixed
 *    HERE, in the bytes the driver gave back, and declared in the log.
 *
 * Where it is: `general_level_idc` is the LAST byte of profile_tier_level
 * (7.3.3: 2+1+5 bits, 32 compatibility bits, 48 constraint bits, 8 level
 * bits = 12 bytes), which in the VPS starts at RBSP byte 4 and in the SPS at
 * byte 1.  ⚠ The RBSP is walked COUNTING the emulation bytes (`00 00 03`):
 * the VPS has some, and the position in the NAL is not the one in the RBSP.
 */
static void fix_hevc_level(VulkanVideo *v)
{
	size_t i = 0;
	int correct = 0;

	while (i + 4 <= v->headers_byte) {
		/* the next NAL: after `00 00 00 01` (or `00 00 01`) */
		size_t start;
		if (v->headers[i] == 0 && v->headers[i + 1] == 0 && v->headers[i + 2] == 0 && v->headers[i + 3] == 1)
			start = i + 4;
		else if (v->headers[i] == 0 && v->headers[i + 1] == 0 && v->headers[i + 2] == 1)
			start = i + 3;
		else {
			i++;
			continue;
		}
		{
			unsigned kind = (v->headers[start] >> 1) & 0x3f;
			size_t wanted_rbsp = kind == 32 ? 4 + 11 : kind == 33 ? 1 + 11 : 0; /* VPS: 4+11 · SPS: 1+11 */
			size_t pos = start + 2, rbsp = 0;
			int zeros = 0;
			if (!wanted_rbsp) {
				i = start;
				continue;
			}
			/* walk the RBSP up to the wanted byte, skipping the emulation `03`s */
			while (pos < v->headers_byte) {
				uint8_t b = v->headers[pos];
				if (zeros >= 2 && b == 3) {
					zeros = 0;
					pos++;
					continue;
				}
				if (rbsp == wanted_rbsp)
					break;
				zeros = b == 0 ? zeros + 1 : 0;
				rbsp++;
				pos++;
			}
			if (pos < v->headers_byte && rbsp == wanted_rbsp
			    && v->headers[pos] != (uint8_t) v->decl.level_idc) {
				registro_dice(LOG_ENCODING,
				              "⚠ vulkanvideo HEVC: the driver wrote general_level_idc %u in the %s, the level "
				              "is %d: fixed in the bytes (RADV uses the H.264 alphabet)",
				              v->headers[pos], kind == 32 ? "VPS" : "SPS", v->decl.level_idc);
				v->headers[pos] = (uint8_t) v->decl.level_idc;
				correct++;
			}
			i = start;
		}
	}
	v->decl.level_fixed_in_bytes = correct > 0;
}

