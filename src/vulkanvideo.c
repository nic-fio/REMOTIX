static bool open_logical_device(VulkanVideoDevice *d, char *error, size_t error_byte)
{
	const char *est[12];
	uint32_t ne = 0;
	float prio = 1.0f;
	VkDeviceQueueCreateInfo code[2] = {
		{ .sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO, .queueFamilyIndex = d->encode_fam,
		  .queueCount = 1, .pQueuePriorities = &prio },
		{ .sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO, .queueFamilyIndex = d->compute_fam,
		  .queueCount = 1, .pQueuePriorities = &prio },
	};
	VkPhysicalDeviceVulkan13Features f13 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_3_FEATURES };
	VkPhysicalDeviceVulkan11Features f11 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_1_FEATURES, .pNext = &f13 };
	VkPhysicalDeviceFeatures2 f2 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2, .pNext = &f11 };
	VkDeviceCreateInfo ci = { .sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO };

	vkGetPhysicalDeviceFeatures2(d->physical, &f2);
	if (!f13.synchronization2)
		FAIL("«%s» lacks synchronization2", d->name);
	if (!f11.samplerYcbcrConversion)
		FAIL("«%s» lacks samplerYcbcrConversion (needed for NV12 images)", d->name);
	d->writes_without_format = f2.features.shaderStorageImageWriteWithoutFormat;
	if (!d->writes_without_format)
		FAIL("«%s» lacks shaderStorageImageWriteWithoutFormat (the shader writes NV12 and P010)", d->name);
	/* only what is needed, switched on: the other features stay off */
	memset(&f2.features, 0, sizeof f2.features);
	f2.features.shaderStorageImageWriteWithoutFormat = VK_TRUE;
	{
		VkPhysicalDeviceVulkan11Features v11 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_1_FEATURES, .pNext = &f13 };
		VkPhysicalDeviceVulkan13Features v13 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_3_FEATURES };
		v11.samplerYcbcrConversion = VK_TRUE;
		v13.synchronization2 = VK_TRUE;
		f11 = v11;
		f13 = v13;
		f11.pNext = &f13;
	}

	est[ne++] = VK_KHR_VIDEO_QUEUE_EXTENSION_NAME;
	est[ne++] = VK_KHR_VIDEO_ENCODE_QUEUE_EXTENSION_NAME;
	if (d->ha_h264)
		est[ne++] = VK_KHR_VIDEO_ENCODE_H264_EXTENSION_NAME;
	if (d->ha_h265)
		est[ne++] = VK_KHR_VIDEO_ENCODE_H265_EXTENSION_NAME;
	if (d->ha_dmabuf) {
		est[ne++] = VK_KHR_EXTERNAL_MEMORY_FD_EXTENSION_NAME;
		est[ne++] = VK_EXT_EXTERNAL_MEMORY_DMA_BUF_EXTENSION_NAME;
		est[ne++] = VK_EXT_IMAGE_DRM_FORMAT_MODIFIER_EXTENSION_NAME;
	}
	if (d->ha_foreign)
		est[ne++] = VK_EXT_QUEUE_FAMILY_FOREIGN_EXTENSION_NAME;
	if (d->ha_maintenance1)
		est[ne++] = VK_KHR_VIDEO_MAINTENANCE_1_EXTENSION_NAME;

	ci.pNext = &f2;
	ci.queueCreateInfoCount = d->encode_fam == d->compute_fam ? 1 : 2;
	ci.pQueueCreateInfos = code;
	ci.enabledExtensionCount = ne;
	ci.ppEnabledExtensionNames = est;
	VK_OR_FAIL(vkCreateDevice(d->physical, &ci, NULL, &d->device), "vkCreateDevice");
	vkGetDeviceQueue(d->device, d->encode_fam, 0, &d->encode_queue);
	if (d->encode_fam == d->compute_fam)
		d->compute_queue = d->encode_queue;
	else
		vkGetDeviceQueue(d->device, d->compute_fam, 0, &d->compute_queue);
	vkGetPhysicalDeviceMemoryProperties(d->physical, &d->mem_buf);

	TAKE_I(GetPhysicalDeviceVideoCapabilitiesKHR);
	TAKE_I(GetPhysicalDeviceVideoFormatPropertiesKHR);
	TAKE_D(CreateVideoSessionKHR);
	TAKE_D(DestroyVideoSessionKHR);
	TAKE_D(GetVideoSessionMemoryRequirementsKHR);
	TAKE_D(BindVideoSessionMemoryKHR);
	TAKE_D(CreateVideoSessionParametersKHR);
	TAKE_D(DestroyVideoSessionParametersKHR);
	TAKE_D(GetEncodedVideoSessionParametersKHR);
	TAKE_D(CmdBeginVideoCodingKHR);
	TAKE_D(CmdEndVideoCodingKHR);
	TAKE_D(CmdControlVideoCodingKHR);
	TAKE_D(CmdEncodeVideoKHR);
	if (d->ha_dmabuf)
		TAKE_D(GetMemoryFdPropertiesKHR);
	return true;
}

VulkanVideoDevice *vulkanvideo_open_device(const char *node, char *error, size_t error_byte)
{
	VulkanVideoDevice *d;
	VkApplicationInfo app = {
		.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO,
		.pApplicationName = "remotix",
		.pEngineName = "remotix-vulkanvideo",
		.apiVersion = VK_API_VERSION_1_3,
	};
	VkInstanceCreateInfo ic = { .sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO, .pApplicationInfo = &app };
	VkResult r;

	if (!node || !node[0]) {
		di(error, error_byte, "vulkanvideo: no DRM node declared — none is guessed");
		return NULL;
	}
	d = calloc(1, sizeof *d);
	if (!d) {
		di(error, error_byte, "out of memory");
		return NULL;
	}
	snprintf(d->node, sizeof d->node, "%s", node);
	r = vkCreateInstance(&ic, NULL, &d->instance);
	if (r != VK_SUCCESS) {
		di(error, error_byte, "vkCreateInstance: %s", vk_name(r));
		free(d);
		return NULL;
	}
	if (!choose_physical_device(d, node, error, error_byte) || !choose_code(d, error, error_byte)
	    || !open_logical_device(d, error, error_byte)) {
		vulkanvideo_close_device(d);
		return NULL;
	}
	return d;
}

void vulkanvideo_close_device(VulkanVideoDevice *d)
{
	if (!d)
		return;
	if (d->device)
		vkDestroyDevice(d->device, NULL);
	if (d->instance)
		vkDestroyInstance(d->instance, NULL);
	free(d);
}

