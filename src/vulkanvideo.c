static uint32_t memory_type(const VulkanVideoDevice *d, uint32_t bits, VkMemoryPropertyFlags wanted_flags)
{
	for (uint32_t i = 0; i < d->mem_buf.memoryTypeCount; i++)
		if ((bits & (1u << i)) && (d->mem_buf.memoryTypes[i].propertyFlags & wanted_flags) == wanted_flags)
			return i;
	return UINT32_MAX;
}

static bool alloc_memory(VulkanVideo *v, const VkMemoryRequirements *req, VkMemoryPropertyFlags wanted_flags,
                   VkMemoryPropertyFlags fallback, const void *pnext, VkDeviceMemory *mem,
                   VkMemoryPropertyFlags *obtained, char *error, size_t error_byte)
{
	uint32_t t = memory_type(v->d, req->memoryTypeBits, wanted_flags);
	VkMemoryAllocateInfo ai = { .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO, .pNext = pnext,
		                        .allocationSize = req->size };
	if (t == UINT32_MAX && fallback)
		t = memory_type(v->d, req->memoryTypeBits, fallback);
	if (t == UINT32_MAX)
		t = memory_type(v->d, req->memoryTypeBits, 0);
	if (t == UINT32_MAX)
		FAIL("no memory type for bits 0x%x", req->memoryTypeBits);
	ai.memoryTypeIndex = t;
	VK_OR_FAIL(vkAllocateMemory(v->d->device, &ai, NULL, mem), "vkAllocateMemory");
	if (obtained)
		*obtained = v->d->mem_buf.memoryTypes[t].propertyFlags;
	return true;
}

