static bool has_extension(const VkExtensionProperties *e, uint32_t n, const char *name)
{
	for (uint32_t i = 0; i < n; i++)
		if (strcmp(e[i].extensionName, name) == 0)
			return true;
	return false;
}

/* The card behind the NODE: `VK_EXT_physical_device_drm` gives the major and
 * minor of each physical device's render node, and they are compared with
 * `stat()` of the requested node.  ⛔ Not "the first device": this machine
 * has three (Radeon, Intel, llvmpipe). */
static bool choose_physical_device(VulkanVideoDevice *d, const char *node, char *error,
                          size_t error_byte)
{
	struct stat st;
	uint32_t amount = 0;
	VkPhysicalDevice listing[16];
	char seen_items[512] = { 0 };

	if (stat(node, &st) != 0)
		FAIL("cannot read node %s: %s", node, strerror(errno));
	VK_OR_FAIL(vkEnumeratePhysicalDevices(d->instance, &amount, NULL), "vkEnumeratePhysicalDevices");
	if (amount > 16)
		amount = 16;
	if (!amount)
		FAIL("no Vulkan device");
	vkEnumeratePhysicalDevices(d->instance, &amount, listing);
	for (uint32_t i = 0; i < amount; i++) {
		uint32_t ne = 0;
		VkExtensionProperties *est;
		VkPhysicalDeviceDrmPropertiesEXT drm = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_DRM_PROPERTIES_EXT };
		VkPhysicalDeviceProperties2 p2 = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2 };
		char piece[160];

		vkEnumerateDeviceExtensionProperties(listing[i], NULL, &ne, NULL);
		est = calloc(ne ? ne : 1, sizeof *est);
		if (!est)
			FAIL("out of memory");
		vkEnumerateDeviceExtensionProperties(listing[i], NULL, &ne, est);
		if (has_extension(est, ne, VK_EXT_PHYSICAL_DEVICE_DRM_EXTENSION_NAME))
			p2.pNext = &drm;
		vkGetPhysicalDeviceProperties2(listing[i], &p2);
		snprintf(piece, sizeof piece, "%s«%s»%s", i ? ", " : "", p2.properties.deviceName,
		         p2.pNext ? "" : " (without VK_EXT_physical_device_drm)");
		strncat(seen_items, piece, sizeof seen_items - strlen(seen_items) - 1);
		if (p2.pNext && ((drm.hasRender && drm.renderMajor == (int64_t) major(st.st_rdev)
		                  && drm.renderMinor == (int64_t) minor(st.st_rdev))
		                 || (drm.hasPrimary && drm.primaryMajor == (int64_t) major(st.st_rdev)
		                     && drm.primaryMinor == (int64_t) minor(st.st_rdev)))) {
			d->physical = listing[i];
			d->ha_drm = true;
			d->ha_h264 = has_extension(est, ne, VK_KHR_VIDEO_ENCODE_H264_EXTENSION_NAME);
			d->ha_h265 = has_extension(est, ne, VK_KHR_VIDEO_ENCODE_H265_EXTENSION_NAME);
			d->ha_dmabuf = has_extension(est, ne, VK_EXT_EXTERNAL_MEMORY_DMA_BUF_EXTENSION_NAME)
			               && has_extension(est, ne, VK_EXT_IMAGE_DRM_FORMAT_MODIFIER_EXTENSION_NAME)
			               && has_extension(est, ne, VK_KHR_EXTERNAL_MEMORY_FD_EXTENSION_NAME);
			d->ha_foreign = has_extension(est, ne, VK_EXT_QUEUE_FAMILY_FOREIGN_EXTENSION_NAME);
			d->ha_maintenance1 = has_extension(est, ne, VK_KHR_VIDEO_MAINTENANCE_1_EXTENSION_NAME);
			bool queue = has_extension(est, ne, VK_KHR_VIDEO_QUEUE_EXTENSION_NAME)
			            && has_extension(est, ne, VK_KHR_VIDEO_ENCODE_QUEUE_EXTENSION_NAME);
			free(est);
			snprintf(d->name, sizeof d->name, "%s", p2.properties.deviceName);
			d->api_version = p2.properties.apiVersion;
			{
				VkPhysicalDeviceDriverProperties dp = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_DRIVER_PROPERTIES };
				VkPhysicalDeviceProperties2 q = { .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2, .pNext = &dp };
				vkGetPhysicalDeviceProperties2(listing[i], &q);
				snprintf(d->driver, sizeof d->driver, "%s %s", dp.driverName, dp.driverInfo);
			}
			if (!queue)
				FAIL("«%s» (%s) on %s lacks VK_KHR_video_encode_queue: no Vulkan encoding",
				         d->name, d->driver, node);
			if (!d->ha_h264 && !d->ha_h265)
				FAIL("«%s» (%s) on %s has the video queue but no encode codec "
				         "(neither VK_KHR_video_encode_h264 nor _h265)", d->name, d->driver, node);
			if (p2.properties.apiVersion < VK_API_VERSION_1_3)
				FAIL("«%s» is Vulkan %u.%u: 1.3 is required", d->name,
				         VK_API_VERSION_MAJOR(p2.properties.apiVersion),
				         VK_API_VERSION_MINOR(p2.properties.apiVersion));
			return true;
		}
		free(est);
	}
	FAIL("no Vulkan device is behind %s (%u:%u); seen: %s", node,
	         major(st.st_rdev), minor(st.st_rdev), seen_items);
}

static bool choose_code(VulkanVideoDevice *d, char *error, size_t error_byte)
{
	uint32_t n = 0;
	VkQueueFamilyProperties2 *fp;
	VkQueueFamilyVideoPropertiesKHR *vp;
	uint32_t encode = UINT32_MAX, compute = UINT32_MAX;

	vkGetPhysicalDeviceQueueFamilyProperties2(d->physical, &n, NULL);
	if (!n)
		FAIL("no queue family");
	fp = calloc(n, sizeof *fp);
	vp = calloc(n, sizeof *vp);
	if (!fp || !vp) {
		free(fp);
		free(vp);
		FAIL("out of memory");
	}
	for (uint32_t i = 0; i < n; i++) {
		fp[i].sType = VK_STRUCTURE_TYPE_QUEUE_FAMILY_PROPERTIES_2;
		vp[i].sType = VK_STRUCTURE_TYPE_QUEUE_FAMILY_VIDEO_PROPERTIES_KHR;
		fp[i].pNext = &vp[i];
	}
	vkGetPhysicalDeviceQueueFamilyProperties2(d->physical, &n, fp);
	for (uint32_t i = 0; i < n; i++) {
		VkQueueFlags fl = fp[i].queueFamilyProperties.queueFlags;
		if ((fl & VK_QUEUE_VIDEO_ENCODE_BIT_KHR)
		    && (vp[i].videoCodecOperations & (VK_VIDEO_CODEC_OPERATION_ENCODE_H264_BIT_KHR
		                                      | VK_VIDEO_CODEC_OPERATION_ENCODE_H265_BIT_KHR))
		    && encode == UINT32_MAX) {
			encode = i;
			d->operations = vp[i].videoCodecOperations;
		}
	}
	/* compute: a family with COMPUTE and TRANSFER, preferably not the graphics
	 * one (so the conversion does not queue behind the compositor). */
	for (uint32_t i = 0; i < n; i++) {
		VkQueueFlags fl = fp[i].queueFamilyProperties.queueFlags;
		if (!(fl & VK_QUEUE_COMPUTE_BIT))
			continue;
		if (compute == UINT32_MAX || (!(fl & VK_QUEUE_GRAPHICS_BIT)
		                              && (fp[compute].queueFamilyProperties.queueFlags & VK_QUEUE_GRAPHICS_BIT)))
			compute = i;
	}
	free(fp);
	free(vp);
	if (encode == UINT32_MAX)
		FAIL("«%s»: no queue family with H.264/HEVC video encoding", d->name);
	if (compute == UINT32_MAX)
		FAIL("«%s»: no queue family with compute", d->name);
	d->encode_fam = encode;
	d->compute_fam = compute;
	return true;
}

