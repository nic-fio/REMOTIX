/* The video profile is a chain of three structures that must be passed
 * IDENTICAL to every object using it (session, images, buffers, queries): it
 * lives in one place and is copied from there. */
typedef struct {
	VkVideoProfileInfoKHR profile;
	VkVideoEncodeUsageInfoKHR usage;
	VkVideoEncodeH264ProfileInfoKHR h264;
	VkVideoEncodeH265ProfileInfoKHR h265;
	VkVideoProfileListInfoKHR items;
} ProfileV;

static void compose_profile(ProfileV *p, VulkanVideoCodec codec, int depth, bool low_latency)
{
	memset(p, 0, sizeof *p);
	p->usage = (VkVideoEncodeUsageInfoKHR){
		.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_USAGE_INFO_KHR,
		.videoUsageHints = VK_VIDEO_ENCODE_USAGE_STREAMING_BIT_KHR,
		.videoContentHints = VK_VIDEO_ENCODE_CONTENT_DESKTOP_BIT_KHR,
		.tuningMode = low_latency ? VK_VIDEO_ENCODE_TUNING_MODE_ULTRA_LOW_LATENCY_KHR
		                             : VK_VIDEO_ENCODE_TUNING_MODE_DEFAULT_KHR,
	};
	if (codec == VULKANVIDEO_H264) {
		p->h264 = (VkVideoEncodeH264ProfileInfoKHR){
			.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H264_PROFILE_INFO_KHR,
			.pNext = &p->usage,
			.stdProfileIdc = STD_VIDEO_H264_PROFILE_IDC_HIGH,
		};
		p->profile.pNext = &p->h264;
		p->profile.videoCodecOperation = VK_VIDEO_CODEC_OPERATION_ENCODE_H264_BIT_KHR;
	} else {
		p->h265 = (VkVideoEncodeH265ProfileInfoKHR){
			.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H265_PROFILE_INFO_KHR,
			.pNext = &p->usage,
			.stdProfileIdc = depth == 10 ? STD_VIDEO_H265_PROFILE_IDC_MAIN_10
			                                  : STD_VIDEO_H265_PROFILE_IDC_MAIN,
		};
		p->profile.pNext = &p->h265;
		p->profile.videoCodecOperation = VK_VIDEO_CODEC_OPERATION_ENCODE_H265_BIT_KHR;
	}
	p->profile.sType = VK_STRUCTURE_TYPE_VIDEO_PROFILE_INFO_KHR;
	p->profile.chromaSubsampling = VK_VIDEO_CHROMA_SUBSAMPLING_420_BIT_KHR;
	p->profile.lumaBitDepth = depth == 10 ? VK_VIDEO_COMPONENT_BIT_DEPTH_10_BIT_KHR
	                                            : VK_VIDEO_COMPONENT_BIT_DEPTH_8_BIT_KHR;
	p->profile.chromaBitDepth = p->profile.lumaBitDepth;
	p->items = (VkVideoProfileListInfoKHR){
		.sType = VK_STRUCTURE_TYPE_VIDEO_PROFILE_LIST_INFO_KHR,
		.profileCount = 1,
		.pProfiles = &p->profile,
	};
}

typedef struct {
	VkVideoCapabilitiesKHR video;
	VkVideoEncodeCapabilitiesKHR encode;
	VkVideoEncodeH264CapabilitiesKHR h264;
	VkVideoEncodeH265CapabilitiesKHR h265;
	VkFormat input_format, dpb_format;
	VkImageUsageFlags input_usage, dpb_usage;
	VkImageCreateFlags input_flag, flag_dpb;
	/* ⛔ `imageUsageFlags` of the video properties is NOT enough: `[M]` 1 Oct 2026
	 *    RADV puts back only the requested usage (0x4000).  What an image can
	 *    do is told by `vkGetPhysicalDeviceImageFormatProperties2` with the
	 *    profile in the chain, and it is asked for both routes. */
	bool direct_input;   /* ENCODE_SRC | STORAGE (with mutable planes): the shader writes the planes */
	bool input_copy;     /* ENCODE_SRC | TRANSFER_DST: the shader writes elsewhere and it is copied */
	bool declared_level; /* `maxLevelIdc` > 1.0: if 0 the driver does not say */
} Capabilities;

/* Can an image with this format, usage and flags be created for this
 * profile?  Three outcomes: yes, no, and "the call failed", which counts as no. */
static bool sustained_use(VulkanVideoDevice *d, const ProfileV *p, VkFormat f, VkImageUsageFlags usage,
                          VkImageCreateFlags flag)
{
	VkPhysicalDeviceImageFormatInfo2 fi = {
		.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_IMAGE_FORMAT_INFO_2, .pNext = &p->items, .format = f,
		.type = VK_IMAGE_TYPE_2D, .tiling = VK_IMAGE_TILING_OPTIMAL, .usage = usage, .flags = flag };
	VkImageFormatProperties2 fp = { .sType = VK_STRUCTURE_TYPE_IMAGE_FORMAT_PROPERTIES_2 };
	return vkGetPhysicalDeviceImageFormatProperties2(d->physical, &fi, &fp) == VK_SUCCESS;
}

static VkFormat wanted_format(int depth)
{
	return depth == 10 ? VK_FORMAT_G10X6_B10X6R10X6_2PLANE_420_UNORM_3PACK16
	                        : VK_FORMAT_G8_B8R8_2PLANE_420_UNORM;
}

static const char *format_name(VkFormat f)
{
	switch (f) {
	case VK_FORMAT_G8_B8R8_2PLANE_420_UNORM: return "NV12 (G8_B8R8_2PLANE_420)";
	case VK_FORMAT_G10X6_B10X6R10X6_2PLANE_420_UNORM_3PACK16: return "P010 (G10X6_B10X6R10X6_2PLANE_420)";
	case VK_FORMAT_G8_B8_R8_3PLANE_420_UNORM: return "I420 (3PLANE_420)";
	default: return "other";
	}
}

static bool profile_formats(VulkanVideoDevice *d, const ProfileV *p, int depth,
                                VkImageUsageFlags usage, VkFormat *fmt, VkImageUsageFlags *uses,
                                VkImageCreateFlags *flag, char *error, size_t error_byte)
{
	VkPhysicalDeviceVideoFormatInfoKHR fi = {
		.sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VIDEO_FORMAT_INFO_KHR,
		.pNext = &p->items,
		.imageUsage = usage,
	};
	uint32_t n = 0;
	VkVideoFormatPropertiesKHR fp[16];
	VkFormat wanted = wanted_format(depth);

	VK_OR_FAIL(d->f.GetPhysicalDeviceVideoFormatPropertiesKHR(d->physical, &fi, &n, NULL),
	              "vkGetPhysicalDeviceVideoFormatPropertiesKHR");
	if (n > 16)
		n = 16;
	if (!n)
		FAIL("the driver declares no image format for usage 0x%x", usage);
	for (uint32_t i = 0; i < n; i++) {
		memset(&fp[i], 0, sizeof fp[i]);
		fp[i].sType = VK_STRUCTURE_TYPE_VIDEO_FORMAT_PROPERTIES_KHR;
	}
	d->f.GetPhysicalDeviceVideoFormatPropertiesKHR(d->physical, &fi, &n, fp);
	for (uint32_t i = 0; i < n; i++) {
		if (fp[i].format == wanted && fp[i].imageType == VK_IMAGE_TYPE_2D
		    && fp[i].imageTiling == VK_IMAGE_TILING_OPTIMAL) {
			*fmt = fp[i].format;
			*uses = fp[i].imageUsageFlags;
			*flag = fp[i].imageCreateFlags;
			return true;
		}
	}
	{
		char seen_items[256] = { 0 };
		for (uint32_t i = 0; i < n; i++) {
			char piece[32];
			snprintf(piece, sizeof piece, "%s%d", i ? "," : "", (int) fp[i].format);
			strncat(seen_items, piece, sizeof seen_items - strlen(seen_items) - 1);
		}
		FAIL("the driver does not offer %s for usage 0x%x (VkFormats seen: %s)", format_name(wanted),
		         usage, seen_items);
	}
}

static bool profile_capabilities(VulkanVideoDevice *d, ProfileV *p, VulkanVideoCodec codec,
                                 int depth, Capabilities *c, char *error, size_t error_byte)
{
	VkResult r;

	if (codec == VULKANVIDEO_H264 && !d->ha_h264)
		FAIL("«%s» lacks VK_KHR_video_encode_h264", d->name);
	if (codec == VULKANVIDEO_HEVC && !d->ha_h265)
		FAIL("«%s» lacks VK_KHR_video_encode_h265", d->name);
	if (codec == VULKANVIDEO_H264 && depth != 8)
		FAIL("H.264 at %d bits does not open (only 8-bit High)", depth);
	if (!(d->operations & (codec == VULKANVIDEO_H264 ? VK_VIDEO_CODEC_OPERATION_ENCODE_H264_BIT_KHR
	                                                  : VK_VIDEO_CODEC_OPERATION_ENCODE_H265_BIT_KHR)))
		FAIL("the encode queue of «%s» does not declare %s", d->name,
		         codec == VULKANVIDEO_H264 ? "H.264" : "HEVC");

	memset(c, 0, sizeof *c);
	c->video.sType = VK_STRUCTURE_TYPE_VIDEO_CAPABILITIES_KHR;
	c->encode.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_CAPABILITIES_KHR;
	c->h264.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H264_CAPABILITIES_KHR;
	c->h265.sType = VK_STRUCTURE_TYPE_VIDEO_ENCODE_H265_CAPABILITIES_KHR;
	c->video.pNext = &c->encode;
	c->encode.pNext = codec == VULKANVIDEO_H264 ? (void *) &c->h264 : (void *) &c->h265;

	r = d->f.GetPhysicalDeviceVideoCapabilitiesKHR(d->physical, &p->profile, &c->video);
	if (r != VK_SUCCESS && p->usage.tuningMode != VK_VIDEO_ENCODE_TUNING_MODE_DEFAULT_KHR) {
		/* the driver does not accept minimum latency: retry with the default, and
		 * declare it (the caller reads `usage.tuningMode`) */
		p->usage.tuningMode = VK_VIDEO_ENCODE_TUNING_MODE_DEFAULT_KHR;
		r = d->f.GetPhysicalDeviceVideoCapabilitiesKHR(d->physical, &p->profile, &c->video);
	}
	if (r != VK_SUCCESS)
		FAIL("vkGetPhysicalDeviceVideoCapabilitiesKHR (%s %d bit): %s",
		         codec == VULKANVIDEO_H264 ? "H.264 High" : "HEVC Main", depth, vk_name(r));
	if (!profile_formats(d, p, depth, VK_IMAGE_USAGE_VIDEO_ENCODE_SRC_BIT_KHR,
	                         &c->input_format, &c->input_usage, &c->input_flag, error,
	                         error_byte))
		return false;
	if (!profile_formats(d, p, depth, VK_IMAGE_USAGE_VIDEO_ENCODE_DPB_BIT_KHR,
	                         &c->dpb_format, &c->dpb_usage, &c->flag_dpb, error, error_byte))
		return false;
	c->direct_input = sustained_use(d, p, c->input_format,
	                                    VK_IMAGE_USAGE_VIDEO_ENCODE_SRC_BIT_KHR | VK_IMAGE_USAGE_STORAGE_BIT,
	                                    VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT | VK_IMAGE_CREATE_EXTENDED_USAGE_BIT);
	c->input_copy = sustained_use(d, p, c->input_format,
	                                  VK_IMAGE_USAGE_VIDEO_ENCODE_SRC_BIT_KHR | VK_IMAGE_USAGE_TRANSFER_DST_BIT, 0);
	c->declared_level = codec == VULKANVIDEO_H264 ? c->h264.maxLevelIdc != STD_VIDEO_H264_LEVEL_IDC_1_0
	                                                   : c->h265.maxLevelIdc != STD_VIDEO_H265_LEVEL_IDC_1_0;
	return true;
}

static void fill_capability_profile(const VulkanVideoDevice *d, VulkanVideoCodec codec,
                                    const Capabilities *c, VulkanVideoProfileCapabilities *f)
{
	f->encode = true;
	f->max_size_w = c->video.maxCodedExtent.width;
	f->max_size_h = c->video.maxCodedExtent.height;
	f->min_size_w = c->video.minCodedExtent.width;
	f->min_size_h = c->video.minCodedExtent.height;
	f->bitrate_modes = 0;
	if (c->encode.rateControlModes & VK_VIDEO_ENCODE_RATE_CONTROL_MODE_DISABLED_BIT_KHR)
		f->bitrate_modes |= VULKANVIDEO_RC_CQP;
	if (c->encode.rateControlModes & VK_VIDEO_ENCODE_RATE_CONTROL_MODE_CBR_BIT_KHR)
		f->bitrate_modes |= VULKANVIDEO_RC_CBR;
	if (c->encode.rateControlModes & VK_VIDEO_ENCODE_RATE_CONTROL_MODE_VBR_BIT_KHR)
		f->bitrate_modes |= VULKANVIDEO_RC_VBR;
	if (codec == VULKANVIDEO_H264) {
		f->qp_min = c->h264.minQp;
		f->qp_max = c->h264.maxQp;
		f->max_level_idc = h264_level_idc(c->h264.maxLevelIdc);
	} else {
		f->qp_min = c->h265.minQp;
		f->qp_max = c->h265.maxQp;
		f->max_level_idc = hevc_level_idc(c->h265.maxLevelIdc);
	}
	f->slot_dpb = c->video.maxDpbSlots;
	f->active_references = c->video.maxActiveReferencePictures;
	f->quality_levels = c->encode.maxQualityLevels;
	f->granularity_w = c->encode.encodeInputPictureGranularity.width;
	f->granularity_h = c->encode.encodeInputPictureGranularity.height;
	f->headers_from_driver = d->f.GetEncodedVideoSessionParametersKHR != NULL;
	snprintf(f->input_format, sizeof f->input_format, "%s", format_name(c->input_format));
	f->input_writable_by_shader = c->direct_input;
	f->syntax = codec == VULKANVIDEO_H264 ? c->h264.stdSyntaxFlags : c->h265.stdSyntaxFlags;
	f->cabac = codec == VULKANVIDEO_H264
	           && (c->h264.stdSyntaxFlags & VK_VIDEO_ENCODE_H264_STD_ENTROPY_CODING_MODE_FLAG_SET_BIT_KHR);
	f->transform_8x8 = codec == VULKANVIDEO_H264
	                   && (c->h264.stdSyntaxFlags & VK_VIDEO_ENCODE_H264_STD_TRANSFORM_8X8_MODE_FLAG_SET_BIT_KHR);
	if (!c->declared_level)
		f->max_level_idc = 0; /* 0 = the driver does not declare it */
}

bool vulkanvideo_capabilities(const char *node, VulkanVideoCapabilities *c, char *error, size_t error_byte)
{
	VulkanVideoDevice *d;
	char why[256] = { 0 };

	if (!c)
		return false;
	memset(c, 0, sizeof *c);
	d = vulkanvideo_open_device(node, why, sizeof why);
	if (!d) {
		c->vulkan_c_e = false;
		snprintf(c->why, sizeof c->why, "%s", why);
		di(error, error_byte, "%s", why);
		return false;
	}
	c->vulkan_c_e = true;
	snprintf(c->card_name, sizeof c->card_name, "%s", d->name);
	snprintf(c->driver, sizeof c->driver, "%s", d->driver);
	c->api_version = d->api_version;
	c->dmabuf = d->ha_dmabuf;
	{
		struct {
			VulkanVideoCodec codec;
			int prof;
			VulkanVideoProfileCapabilities *dove;
		} tre[3] = { { VULKANVIDEO_H264, 8, &c->h264 }, { VULKANVIDEO_HEVC, 8, &c->hevc },
			         { VULKANVIDEO_HEVC, 10, &c->hevc10 } };
		for (int i = 0; i < 3; i++) {
			ProfileV p;
			Capabilities cap;
			char e[256] = { 0 };
			compose_profile(&p, tre[i].codec, tre[i].prof, true);
			if (profile_capabilities(d, &p, tre[i].codec, tre[i].prof, &cap, e, sizeof e))
				fill_capability_profile(d, tre[i].codec, &cap, tre[i].dove);
			else
				tre[i].dove->encode = false;
		}
	}
	vulkanvideo_close_device(d);
	return true;
}

