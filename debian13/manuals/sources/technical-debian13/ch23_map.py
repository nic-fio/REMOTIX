def _manual_rows():
    import pathlib
    from build import HERE, ROOT
    rows = []
    for f in sorted(HERE.rglob("*")):
        if f.is_file() and f.suffix in (".py", ".css", ".js") and "__pycache__" not in f.parts:
            rel = f.relative_to(ROOT).as_posix()
            if f.name == "build.py":
                role = "generator of both manuals"
            elif f.name == "style.css":
                role = "common style (canon, not modified)"
            elif f.name == "manual.js":
                role = "common script: search, copy button (canon, not modified)"
            elif "technical-debian13" in rel:
                role = "chapter of this manual"
            else:
                role = "chapter of the User Manual"
            rows.append((rel, role))
    return rows

MAP[-1] = (MAP[-1][0], _manual_rows())

