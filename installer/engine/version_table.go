package engine

import (
	"fmt"
	"strings"
)

// VersionTable generates from the catalogue the tables of §3.1 (the distributions, the ones out, the
// components' minimum versions). The catalogue is the SINGLE SOURCE: the technical manual is regenerated from
// here at every release, not copied by hand.
func VersionTable(c *Catalog) string {
	var b strings.Builder
	fmt.Fprintf(&b, "*Generated by remotix-install catalog --table, catalogue %s (sequence %d).*\n\n", c.Ver, c.Sequence)
	fmt.Fprintf(&b, "**Distributions**\n\n| distribution | minimum version | status | desktops | conditions |\n|---|---|---|---|---|\n")
	for _, p := range c.Platforms {
		var desk, cond []string
		seen_items := map[string]bool{}
		put := func(x string) {
			if !seen_items[x] {
				seen_items[x] = true
				cond = append(cond, x)
			}
		}
		if len(p.H264.NoStockH264) > 0 {
			put("H.264 on " + strings.Join(p.H264.NoStockH264, " and ") + ": a VA-API driver with H.264, not in the distribution's packages")
		}
		for _, d := range p.Repositories {
			put(notEmpty(c.Repositories[d].Nome, d) + " enabled")
		}
		for _, d := range DESKTOP {
			dc, ok := p.Desktop[d]
			if !ok || !dc.Supported {
				continue
			}
			desk = append(desk, DesktopName(d))
			for _, k := range dc.Components {
				if k == "labwc" {
					continue // the package for XFCE and LXQt always brings it: it is not a peculiarity
				}
				put("`" + k + "` (" + DesktopName(d) + ")")
			}
			for _, k := range dc.Limits {
				put(k)
			}
			// on openSUSE the lxqt pattern brings the scalable font only as recommended (§11.1)
			if d == "lxqt" && dc.NeedsCharacter && p.Famiglia == "suse" {
				put("a scalable font for LXQt")
			}
		}
		if len(cond) == 0 {
			cond = []string{"—"}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", p.Distrib, boldVersion(p.VersionLabel),
			statePlatform(p), strings.Join(desk, ", "), strings.Join(cond, "; "))
	}
	for _, p := range c.Platforms {
		for _, d := range p.Derivatives {
			v := d.MinVersion
			if v == "" {
				v = strings.Join(d.Vers, ", ")
				if v == "*" {
					v = "rolling"
				}
			}
			note := "as " + p.Distrib
			if d.Nota != "" {
				note += "; " + d.Nota
			}
			fmt.Fprintf(&b, "| %s | %s | compatible, not certified | as %s | %s |\n", d.Nome, v, p.Nome, note)
		}
	}
	fmt.Fprintf(&b, "\n**Excluded, and why**\n\n")
	for _, e := range c.Excluded {
		fmt.Fprintf(&b, "- %s %s: %s\n", e.ID, strings.Join(e.Vers, ", "), e.Motivo)
	}
	for _, x := range c.AlwaysOut {
		fmt.Fprintf(&b, "- %s\n", x)
	}
	fmt.Fprintf(&b, "\n**Minimum component versions**\n\n| component | minimum | why |\n|---|---|---|\n")
	for _, k := range c.MinComponents {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", k.Component, k.Minimum, k.Why)
	}
	return b.String()
}

func boldVersion(s string) string {
	first, rest, _ := strings.Cut(s, " ")
	if rest != "" {
		return "**" + first + "** " + rest
	}
	return "**" + first + "**"
}

func statePlatform(p PlatformV) string {
	switch {
	case p.Matrix && p.FullRound != "":
		return "certified (full run of " + p.FullRound + ")"
	case p.Matrix:
		return "in the matrix: certified at the full run (T10)"
	}
	return "analysed, outside the matrix"
}
