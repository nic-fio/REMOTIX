// T: a text of the interface.
func T(key_id string, args ...any) string {
	t, ok := texts[key_id]
	if !ok {
		return "⟨" + key_id + "⟩"
	}
	if len(args) == 0 {
		return t
	}
	return fmt.Sprintf(t, args...)
}
