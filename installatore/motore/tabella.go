package motore

import (
	"fmt"
	"strings"
)

// TabellaVersioni generates from the catalogue the tables of §3.1 (the distributions, the ones out, the
// components' minimum versions). The catalogue is the SINGLE SOURCE: the technical manual is regenerated from
// here at every release, not copied by hand.
func TabellaVersioni(c *Catalogo) string {
	var b strings.Builder
	fmt.Fprintf(&b, "*Generated by remotix-install catalog --table, catalogue %s (sequence %d).*\n\n", c.Ver, c.Sequenza)
	fmt.Fprintf(&b, "**Distributions**\n\n| distribution | minimum version | status | desktops | conditions |\n|---|---|---|---|---|\n")
	for _, p := range c.Platforms {
		var desk, cond []string
		visti := map[string]bool{}
		metti := func(x string) {
			if !visti[x] {
				visti[x] = true
				cond = append(cond, x)
			}
		}
		if len(p.H264.NoStockH264) > 0 {
			metti("H.264 on " + strings.Join(p.H264.NoStockH264, " and ") + ": a VA-API driver with H.264, not in the distribution's packages")
		}
		for _, d := range p.Depositi {
			metti(notEmpty(c.Depositi[d].Nome, d) + " enabled")
		}
		for _, d := range DESKTOP {
			dc, ok := p.Desktop[d]
			if !ok || !dc.Supportato {
				continue
			}
			desk = append(desk, NomeDesktop(d))
			for _, k := range dc.Componenti {
				if k == "labwc" {
					continue // the package for XFCE and LXQt always brings it: it is not a peculiarity
				}
				metti("`" + k + "` (" + NomeDesktop(d) + ")")
			}
			for _, k := range dc.Limiti {
				metti(k)
			}
			// on openSUSE the lxqt pattern brings the scalable font only as recommended (§11.1)
			if d == "lxqt" && dc.NeedsCharacter && p.Famiglia == "suse" {
				metti("a scalable font for LXQt")
			}
		}
		if len(cond) == 0 {
			cond = []string{"—"}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", p.Distrib, boldVersion(p.VersionLabel),
			statePlatform(p), strings.Join(desk, ", "), strings.Join(cond, "; "))
	}
	for _, p := range c.Platforms {
		for _, d := range p.Derivate {
			v := d.MinVersion
			if v == "" {
				v = strings.Join(d.Vers, ", ")
				if v == "*" {
					v = "rolling"
				}
			}
			nota := "as " + p.Distrib
			if d.Nota != "" {
				nota += "; " + d.Nota
			}
			fmt.Fprintf(&b, "| %s | %s | compatible, not certified | as %s | %s |\n", d.Nome, v, p.Nome, nota)
		}
	}
	fmt.Fprintf(&b, "\n**Excluded, and why**\n\n")
	for _, e := range c.Escluse {
		fmt.Fprintf(&b, "- %s %s: %s\n", e.ID, strings.Join(e.Vers, ", "), e.Motivo)
	}
	for _, x := range c.AlwaysOut {
		fmt.Fprintf(&b, "- %s\n", x)
	}
	fmt.Fprintf(&b, "\n**Minimum component versions**\n\n| component | minimum | why |\n|---|---|---|\n")
	for _, k := range c.MinComponents {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", k.Componente, k.Minimo, k.Perche)
	}
	return b.String()
}

func boldVersion(s string) string {
	primo, resto, _ := strings.Cut(s, " ")
	if resto != "" {
		return "**" + primo + "** " + resto
	}
	return "**" + primo + "**"
}

func statePlatform(p PlatformV) string {
	switch {
	case p.Matrice && p.FullRound != "":
		return "certified (full run of " + p.FullRound + ")"
	case p.Matrice:
		return "in the matrix: certified at the full run (T10)"
	}
	return "analysed, outside the matrix"
}
